/**
 * Creates portable text block objects compatible with PortableTextLite component.
 */
function createBlocks(paragraphs: string[]) {
  return paragraphs.map((p, idx) => ({
    _key: `block_${idx}`,
    _type: 'block',
    style: 'normal',
    children: [
      {
        _key: `span_${idx}`,
        _type: 'span',
        marks: [],
        text: p,
      },
    ],
  }))
}

