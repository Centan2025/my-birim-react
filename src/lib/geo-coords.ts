/**
 * Resolves city coordinates by looking into Turkey cities and Global cities
 */
export function getCityCoordinates(
  cityName: string,
  countryName?: string
): [number, number] | null {
  if (!cityName || cityName === 'Unknown' || cityName === '(not set)') return null

  // 1. Exact match in TURKEY_CITY_COORDS
  if (TURKEY_CITY_COORDS[cityName]) {
    return TURKEY_CITY_COORDS[cityName]
  }

  // 2. Exact match in GLOBAL_CITY_COORDS
  if (GLOBAL_CITY_COORDS[cityName]) {
    return GLOBAL_CITY_COORDS[cityName]
  }

  // 3. Case-insensitive / normalized lookup
  const cleanCity = cityName.trim().toLowerCase()

  for (const [k, v] of Object.entries(TURKEY_CITY_COORDS)) {
    if (k.toLowerCase() === cleanCity) return v
  }

  for (const [k, v] of Object.entries(GLOBAL_CITY_COORDS)) {
    if (k.toLowerCase() === cleanCity) return v
  }

  // 4. Fallback to Country Coords if country is given
  if (countryName && COUNTRY_COORDS[countryName]) {
    return COUNTRY_COORDS[countryName]
  }

  return null
}

/**
 * Returns flag emoji for a given country name
 */
export function getCountryFlag(countryName: string): string {
  if (!countryName) return '🌍'
  const meta = COUNTRY_META[countryName]
  if (meta) return meta.flag

  // Alias lookup
  for (const item of Object.values(COUNTRY_META)) {
    if (item.aliases.some(a => a.toLowerCase() === countryName.toLowerCase())) {
      return item.flag
    }
  }

  return '🌍'
}

/**
 * Normalizes GA4 country names to TopoJSON geography names for polygon mapping
 */
export function isCountryMatch(geoName: string, targetCountry: string): boolean {
  if (!geoName || !targetCountry) return false
  if (geoName.toLowerCase() === targetCountry.toLowerCase()) return true

  const meta = COUNTRY_META[targetCountry]
  if (meta) {
    if (meta.aliases.some(a => a.toLowerCase() === geoName.toLowerCase())) {
      return true
    }
  }

  // Handle common discrepancies
  if (
    (targetCountry === 'United States' || targetCountry === 'USA') &&
    geoName === 'United States of America'
  ) {
    return true
  }
  if (
    (targetCountry === 'Turkey' || targetCountry === 'Türkiye') &&
    (geoName === 'Turkey' || geoName === 'Türkiye')
  ) {
    return true
  }
  if (targetCountry === 'Czechia' && (geoName === 'Czech Rep.' || geoName === 'Czech Republic')) {
    return true
  }
  if (targetCountry === 'United Kingdom' && (geoName === 'United Kingdom' || geoName === 'UK')) {
    return true
  }

  return false
}
